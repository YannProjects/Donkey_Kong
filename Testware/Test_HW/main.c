// Sound effects get their own registers
#define  REG_SFX		0x7d00   // The first of 8 sound registers, but only the first 6 are used

// These are added to REG_SFX to produce the register to write to
// These are also used by RAM (@TODO@ -- what variable?) to queue sounds
#define SFX_WALK        0
#define SFX_JUMP        1
#define SFX_BOOM        2       // DK pounds ground; barrel hits Mario
#define SFX_SPRING      3       // (writes to i8035's P1)
#define SFX_FALL        4       // (writes to i8035's P2)
#define SFX_POINTS      5       // Got points, grabbed the hammer, etc.
#define SFX_DEATH       6

#define REG_SFX_DEATH   0x7d80   // plays when Mario dies (triggers i8035's interrupt)

void Test_SoundFx()
{
	char *sound_fx_string;
	unsigned int sound_fx;

	sprintf(SendBuffer, "Effet sonore a activer ? : \n\r");
	UartSendBuffer(SendBuffer, strlen(SendBuffer));
	sprintf(SendBuffer, "1. Walk\n\r2. Jump\n\r3. Boom\n\r4. Spring\n\r5. Fall\n\r6. Points\n\r7. Death\n\r");
	UartSendBuffer(SendBuffer, strlen(SendBuffer));

	sound_fx_string = UartReadLn();
	sscanf((char *)sound_fx_string, "%d", &sound_fx);
	sound_fx -= 1; // Adjust for 0-based indexing

	sprintf(SendBuffer, "Activation SFX pattern id %d\n\rDeclencher le reset pour sortir du mode de test\n\r", sound_fx);
	UartSendBuffer(SendBuffer, strlen(SendBuffer));

	while(1) {
		// Sons analogiques
		if ((sound_fx == SFX_WALK) | (sound_fx == SFX_JUMP) | (sound_fx == SFX_BOOM)) {
			*(unsigned char *)(REG_SFX + sound_fx) = 1;
			sleep_ms(500);
			*(unsigned char *)(REG_SFX + sound_fx) = 0;
		// Sons generes par le microcontroleur i8035
		} else if ((sound_fx == SFX_SPRING) | (sound_fx == SFX_FALL) | (sound_fx == SFX_POINTS)) {
			*(unsigned char *)(REG_SFX + sound_fx) = 1;
			sleep_ms(500);
			*(unsigned char *)(REG_SFX + sound_fx) = 0;
		} else if (sound_fx == SFX_DEATH) {
			*(unsigned char *)(REG_SFX_DEATH) = 1;
			sleep_ms(500);
			*(unsigned char *)(REG_SFX_DEATH) = 0;
		}
		sleep_ms(500);
	}
}


